export type DbCommentPoint = {
    type: 'point';
    selector: string;
    xNormal: number;
    yNormal: number;
};

export type DbCommentSelection = {
    type: 'text';
    text: string;
    startSelector: string;
    startOffset: number;
    startType: 'text' | 'element';
    endSelector?: string;
    endOffset: number;
    endType: 'text' | 'element';
};

/** Feedback about the page as a whole (feedback and bug reports), not pinned to an element */
export type DbCommentPage = {
    type: 'page';
};

export type DbCommentPosition = DbCommentPoint | DbCommentSelection | DbCommentPage;

/**
 * A comment on the page (pinned), general feedback or a bug report (`page` position), or a rewrite
 * suggestion for selected text (its first item is the suggested text, `quotedText` the original)
 */
export type DbCommentKind = 'comment' | 'feedback' | 'bug' | 'rewrite';

export type DbDeviceSize = 'desktop' | 'tablet' | 'mobile';

export type DbCommentDevice = {
    size?: DbDeviceSize;
    windowSize?: [number, number];
    pixelRatio?: number;
    browser?: string;
    os?: string;
};

export type DbThreadItem = {
    /** `item_<nanoid>` generated by the server (old documents: client-generated ids) */
    id: string;
    text: string;
    quotedText?: string;
    /**
     * sha256 of the visitor token (missing on old documents). In a project: `user:<userId>` for a
     * signed-in member, the sha256 of the guest's visitor token for a guest.
     */
    authorId?: string;
    /** Project comments by guests: the name they gave (members' names come from their account) */
    authorName?: string;
    /** ISO 8601, server time (missing on old documents) */
    createdAt?: string;
    /** ISO 8601, server time; set when the text was edited */
    editedAt?: string;
    /**
     * ISO 8601, server time. Set on the first item when its author deleted it after other visitors
     * replied: the item stays as a placeholder ("Comment deleted"), its text is empty and its quoted
     * text and author are removed.
     */
    deletedAt?: string;
};

export type DbComment = {
    /** `comment_<nanoid>` generated by the server */
    id: string;
    /** Partition key: request host, or `project:<projectCode>` for the comments of a project */
    domain: string;
    /** Project comments: the project code */
    projectId?: string;
    /** Project comments: the origin of the site the comment was left on (e.g. a staging address) */
    origin?: string;
    /** Project comments: only workspace admins and the author see it */
    private?: boolean;
    /** Project comments: the user id of the member it is assigned to */
    assigneeId?: string;
    /** Page path without query string and without a trailing slash (except "/") */
    path: string;
    position: DbCommentPosition;
    /** Public id, numbered per domain (`#12`); missing on old documents */
    number?: number;
    /** Missing on old documents: `comment` */
    kind?: DbCommentKind;
    thread: { items: DbThreadItem[] };
    device?: DbCommentDevice;
    /**
     * A screenshot of the commented part of the page, taken by the author when posting: its image
     * is a {@link DbScreenshot} document. Removed with the author's first item.
     */
    screenshot?: DbCommentScreenshot;
    resolved?: boolean;
    /** sha256 of the visitor token (missing on old documents) */
    authorId?: string;
    /** ISO 8601, server time (missing on old documents) */
    createdAt?: string;
    updatedAt?: string;
    /** Seconds; Cosmos DB per-item TTL (requires container defaultTtl = -1 or a positive default) */
    ttl?: number;
};

/**
 * A rate-limit counter for one subject and time window (comments/rateLimits.ts). Stored in the
 * comments container with a short TTL; it has no `path`, so comment queries never match it.
 */
export type DbCounter = {
    /** `counter_<keyed hash of the subject and window>` */
    id: string;
    domain: string;
    type: 'counter';
    count: number;
    ttl: number;
};

/**
 * The domain's comment numbers (`DbComment.number`): one document per domain, incremented
 * atomically. No `ttl` of its own (and no `path`, so comment queries never match it).
 */
export type DbSequence = {
    /** {@link commentSequenceId} */
    id: string;
    domain: string;
    type: 'sequence';
    count: number;
};

/**
 * Id of the comment numbers' sequence. Not an id the API accepts (`isValidId`: no `$`), so no
 * comment route can read, change or delete it.
 */
export const commentSequenceId = '$sequence_comments';

/** What a comment knows about its screenshot (the image itself is a {@link DbScreenshot}) */
export type DbCommentScreenshot = {
    contentType: 'image/webp' | 'image/jpeg' | 'image/png';
    /** Pixels, read from the image */
    width: number;
    height: number;
    bytes: number;
};

/**
 * A comment's screenshot image, a document of its own in the comment's partition (comment lists
 * stay small). No `path`, so comment queries never match it, and an id no route accepts.
 */
export type DbScreenshot = DbCommentScreenshot & {
    /** {@link screenshotDocumentId} of the comment */
    id: string;
    domain: string;
    type: 'screenshot';
    commentId: string;
    /** The image, base64 */
    data: string;
    createdAt: string;
    /** Like the comment's, when it has one */
    ttl?: number;
};

/** Id of a comment's screenshot document: not an id the API accepts (`isValidId`: no `$`) */
export function screenshotDocumentId(commentId: string) {
    return `$screenshot_${commentId}`;
}

/**
 * Whether a document of the comments container is a comment. Rate-limit counters, the sequence
 * and screenshots share its partitions; they have no `path`.
 */
export function isCommentDocument(document: object): boolean {
    const { path, type } = document as { path?: unknown; type?: unknown };
    return typeof path === 'string' && type !== 'counter' && type !== 'sequence' && type !== 'screenshot';
}
