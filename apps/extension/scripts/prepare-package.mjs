import { execFileSync } from 'node:child_process';
import { readFile, rm, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { validate } from './validate.mjs';
const root = resolve(import.meta.dirname, '..');
const { version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const zip = resolve(root, `release/uier-extension-${version}.zip`);
const metadata = JSON.parse(await readFile(`${zip}.json`, 'utf8'));
assert.equal(createHash('sha256').update(await readFile(zip)).digest('hex'), metadata.sha256, 'Package checksum mismatch');
const paths = execFileSync('unzip', ['-Z1', zip], { encoding: 'utf8' }).trim().split('\n');
assert(paths.every(path => !path.startsWith('/') && !path.split('/').includes('..') && !path.includes('\\')), 'Unsafe ZIP path');
const directory = resolve(root, 'test-package');
await rm(directory, { recursive: true, force: true });
await mkdir(directory);
execFileSync('unzip', ['-q', zip, '-d', directory]);
const result = await validate(directory);
assert.deepEqual(result.files, metadata.files, 'Packaged file inventory differs');
console.log(`Testing unchanged production ZIP ${version} (${metadata.sha256})`);
